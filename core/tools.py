"""Research tools that plugins need, installed on demand into the data volume.

Each tool lives in DATA/tools/<id>/ with its own Python environment or binary.
A tool counts as installed only once its marker file names the current recipe
version, so an interrupted or outdated installation is reinstalled. System
libraries (Chromium, ExifTool, FFmpeg, libGL) stay in the container image
because the application cannot install operating-system packages.
"""

from dataclasses import dataclass
import hashlib
import io
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import tarfile
import threading
import urllib.request

from core.errors import AppError

PIP = ["--disable-pip-version-check", "--no-input", "--no-cache-dir"]
MARKER = ".installed.json"
# Hash-pinned dependency locks, regenerated by scripts/lock_tools.py.
LOCKS = Path(__file__).resolve().parent / "tool_locks"
_root = None
# False when ARGUS_TOOLS_DIR points at tools managed outside ARGUS (a CI image
# with preinstalled tools): ARGUS then installs into it but never deletes.
_owned = True
_lock = threading.Lock()


def configure(data_directory):
    """Tools live in the data volume unless ARGUS_TOOLS_DIR provides them."""
    global _root, _owned
    override = os.environ.get("ARGUS_TOOLS_DIR")
    _root = Path(override) if override else Path(data_directory) / "tools"
    _owned = not override
    _root.mkdir(parents=True, exist_ok=True)


def root():
    if _root is None:
        configure(
            os.environ.get("DATA_DIR", Path(__file__).resolve().parents[1] / "data")
        )
    return _root


def directory(tool):
    return root() / tool


def python(tool):
    """Interpreter of a tool's environment; raises if the tool is missing."""
    require(tool)
    return str(directory(tool) / "venv" / "bin" / "python")


def executable(tool, name):
    require(tool)
    candidate = directory(tool) / "venv" / "bin" / name
    if not candidate.exists():
        candidate = directory(tool) / "bin" / name
    return str(candidate)


def source(tool):
    require(tool)
    return directory(tool) / "src"


def site_packages(tool):
    require(tool)
    found = sorted((directory(tool) / "venv" / "lib").glob("python*/site-packages"))
    if not found:
        raise AppError("tool_missing", 409)
    return found[-1]


def installed(tool):
    recipe = RECIPES.get(tool)
    marker = directory(tool) / MARKER
    if not recipe or not marker.is_file():
        return False
    try:
        return json.loads(marker.read_text()).get("version") == recipe.version
    except (OSError, ValueError):
        return False


def require(tool):
    if not installed(tool):
        raise AppError("tool_missing", 409)


def status():
    return {
        tool: {
            "installed": installed(tool),
            "label": recipe.label,
            "size": _size(directory(tool)) if installed(tool) else 0,
        }
        for tool, recipe in RECIPES.items()
    }


def _size(path):
    total = 0
    for base, _, files in os.walk(path):
        for name in files:
            try:
                total += (Path(base) / name).lstat().st_size
            except OSError:
                pass
    return total


class Installation:
    """Install one tool in place; the marker is written only after every step."""

    def __init__(self, tool, log):
        self.tool, self.log = tool, log
        self.path = directory(tool)

    def run(self, command, **kwargs):
        self.log("$ " + " ".join(str(part) for part in command))
        completed = subprocess.run(
            [str(part) for part in command],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            check=False,
            env={**os.environ, "PIP_NO_INPUT": "1"},
            **kwargs,
        )
        for line in completed.stdout.splitlines()[-40:]:
            self.log(line)
        if completed.returncode != 0:
            raise AppError("tool_install_failed", 502)

    def venv(self):
        """A fresh environment with exactly the locked, hash-verified packages."""
        self.run([sys.executable, "-m", "venv", self.path / "venv"])
        self.pip("--require-hashes", "-r", LOCKS / f"{self.tool}.txt")

    def pip(self, *arguments):
        self.run(
            [self.path / "venv/bin/python", "-m", "pip", "install", *PIP, *arguments]
        )

    def fetch(self, url, limit):
        self.log("GET " + url)
        request = urllib.request.Request(url, headers={"User-Agent": "ARGUS-tools"})
        with urllib.request.urlopen(request, timeout=60) as response:
            payload = response.read(limit + 1)
        if len(payload) > limit:
            raise AppError("tool_download_too_large", 502)
        return payload

    def github_source(self, repository, commit, target="src"):
        payload = self.fetch(
            f"https://codeload.github.com/{repository}/tar.gz/{commit}",
            200 * 1024 * 1024,
        )
        extracted = self.path / ".extract"
        with tarfile.open(fileobj=io.BytesIO(payload)) as archive:
            archive.extractall(extracted, filter="data")
        (folder,) = list(extracted.iterdir())
        folder.rename(self.path / target)
        extracted.rmdir()
        (self.path / target / "ARGUS_PIN").write_text(commit + "\n")


@dataclass(frozen=True)
class Recipe:
    label: str
    version: str
    steps: object


def _locked(check):
    """Recipe for a tool that is fully described by its lock file."""

    def steps(job):
        job.venv()
        job.run([job.path / "venv/bin/python", "-c", check])

    return steps


