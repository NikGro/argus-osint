def install(tool, log=lambda line: None):
    """Install a tool unless the current recipe version is already present."""
    if tool not in RECIPES:
        raise AppError("tool_unknown", 404)
    with _lock:
        if installed(tool):
            return False
        path = directory(tool)
        shutil.rmtree(path, ignore_errors=True)
        path.mkdir(parents=True)
        recipe = RECIPES[tool]
        try:
            recipe.steps(Installation(tool, log))
        except Exception:
            shutil.rmtree(path, ignore_errors=True)
            raise
        (path / MARKER).write_text(json.dumps({"version": recipe.version}))
        return True


def remove(tool):
    """Delete an unused tool; externally managed tool directories stay intact."""
    if not _owned:
        return
    with _lock:
        shutil.rmtree(directory(tool), ignore_errors=True)
