PHONEINFOGA = "v2.11.0"


def _phoneinfoga(job):
    arch = {"x86_64": "x86_64", "aarch64": "arm64", "arm64": "arm64"}.get(
        platform.machine()
    )
    if not arch:
        raise AppError("tool_unsupported_platform", 409)
    base = f"https://github.com/sundowndev/phoneinfoga/releases/download/{PHONEINFOGA}/"
    name = f"phoneinfoga_Linux_{arch}.tar.gz"
    checksums = job.fetch(base + "phoneinfoga_checksums.txt", 65536).decode()
    expected = next(
        line.split()[0]
        for line in checksums.splitlines()
        if line.split()[-1].lstrip("*") == name
    )
    payload = job.fetch(base + name, 30 * 1024 * 1024)
    if hashlib.sha256(payload).hexdigest() != expected:
        raise AppError("tool_checksum_mismatch", 502)
    with tarfile.open(fileobj=io.BytesIO(payload), mode="r:gz") as archive:
        member = next(
            item
            for item in archive.getmembers()
            if Path(item.name).name == "phoneinfoga" and item.isfile()
        )
        target = job.path / "bin" / "phoneinfoga"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(archive.extractfile(member).read())
        target.chmod(0o755)
    job.run([target, "version"])


